/**
 * Вертикальная сетка волосных линий внутри секции.
 *
 * Это не повторяющийся градиент, а настоящие блоки шириной 1px. Ставится
 * под содержимое секции: полупрозрачные карточки пропускают линии сквозь
 * себя, непрозрачные картинки — перекрывают, как в оригинале.
 *
 * Раньше сетка была одна на всю страницу и приклеена к экрану. Так она не
 * работала: у каждой секции непрозрачный фон и свой z-index, и общая сетка
 * оставалась под ними — не видно нигде, кроме первого экрана, где она как
 * раз мешала. Секция сама носит свою сетку — и цвет линий берётся от её
 * текста, светлый на тёмной, тёмный на светлой.
 */
export default function GridLines({ count = 7 }: { count?: number }) {
  return (
    <div className="grid-lines" aria-hidden="true">
      {Array.from({ length: count }).map((_, i) => (
        <i
          key={i}
          className={
            i === 1 || i === count - 2
              ? 'hidden lg:block'
              : i === 2 || i === count - 3
                ? 'hidden md:block'
                : ''
          }
        />
      ))}
    </div>
  )
}
